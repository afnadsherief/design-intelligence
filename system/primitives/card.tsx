import * as React from "react";
import { cn } from "@/tooling/utils";

/* ==========================================
   CARD PRIMITIVE
   Uses tokens from tokens/component.css via rgb(var()) pattern.
   Contract: system/contracts/component-contracts.ts
   ========================================== */

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[var(--card-radius)] border border-[var(--border-default)] bg-[rgb(var(--surface-elevated))] text-[rgb(var(--text-primary))] shadow-[var(--card-shadow)]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

